/**
 * Pre-renders a thumbnail of every model's finished state, plus crease patterns, into src/generated/thumbs.ts.
 * Runs before the build so the index pages need no simulation code at all.
 */
import { writeFileSync } from 'node:fs';
import { compile } from '../src/engine/model';
import { frameBox, frameToSvg } from '../src/engine/render';
import { models } from '../src/models/registry';
import type { V2 } from '../src/engine/geom';

const out: Record<string, string> = {};
const cps: Record<string, string> = {};
const r = (n: number) => Math.round(n * 1000) / 1000;

for (const m of models) {
  const def = (await m.load()).default;
  const c = compile(def);
  const last = c.plans[c.plans.length - 1];
  const fr = last.frame(1);
  const box = frameBox(fr, c.size, 0.08);
  out[m.id] = frameToSvg(fr, box, def.palette, c.size, box.w / 200).replace(/(\d+\.\d{2})\d+/g, '$1');

  // crease pattern: every facet edge, drawn in paper coordinates (what you see when you unfold the model)
  const flat = last.end;
  const seen = new Set<string>();
  let d = '';
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  for (const f of flat.facets) {
    const p = f.paper;
    for (let i = 0; i < p.length; i++) {
      const a: V2 = p[i];
      const b: V2 = p[(i + 1) % p.length];
      for (const q of [a, b]) {
        x0 = Math.min(x0, q[0]); x1 = Math.max(x1, q[0]); y0 = Math.min(y0, q[1]); y1 = Math.max(y1, q[1]);
      }
      if (f.soft?.[i]) continue;
      const k = [r(a[0]), r(a[1]), r(b[0]), r(b[1])];
      const key = k[0] < k[2] || (k[0] === k[2] && k[1] < k[3]) ? k.join() : [k[2], k[3], k[0], k[1]].join();
      if (seen.has(key)) continue;
      seen.add(key);
      d += `M${k[0]} ${-k[1]}L${k[2]} ${-k[3]}`;
    }
  }
  const pad = 0.04;
  cps[m.id] = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${r(x0 - pad)} ${r(-y1 - pad)} ${r(x1 - x0 + 2 * pad)} ${r(y1 - y0 + 2 * pad)}"><rect x="${r(x0)}" y="${r(-y1)}" width="${r(x1 - x0)}" height="${r(y1 - y0)}" fill="var(--card)"/><path d="${d}" fill="none" stroke="currentColor" stroke-width="0.008" stroke-linecap="round"/></svg>`;
}

writeFileSync(
  new URL('../src/generated/thumbs.ts', import.meta.url),
  `// Generated by scripts/gen-thumbs.ts — do not edit.\nexport const THUMBS: Record<string, string> = ${JSON.stringify(out)};\nexport const CPS: Record<string, string> = ${JSON.stringify(cps)};\n`,
);
console.log('thumbnails:', Object.keys(out).length, 'bytes:', JSON.stringify(out).length + JSON.stringify(cps).length);
